SELECT (SELECT COUNT(*) FROM users) AS users_rows,
       (SELECT COUNT(*) FROM api_keys) AS api_keys_rows,
       (SELECT COUNT(*) FROM api_keys WHERE status=1) AS api_keys_active,
       (SELECT COUNT(*) FROM orders) AS orders_rows,
       (SELECT COUNT(*) FROM channels) AS channels_rows,
       (SELECT COUNT(*) FROM payment_types) AS pt_rows,
       (SELECT COUNT(*) FROM system_config) AS cfg_rows,
       (SELECT COUNT(*) FROM daily_stats) AS stats_rows,
       (SELECT COUNT(*) FROM settlements) AS settle_rows,
       (SELECT COUNT(*) FROM refunds) AS refund_rows,
       (SELECT COUNT(*) FROM operation_logs) AS oplog_rows,
       (SELECT COUNT(*) FROM password_resets) AS pwdreset_rows,
       (SELECT COUNT(*) FROM throttle_counters) AS throttle_rows,
       (SELECT COUNT(*) FROM user_groups) AS grp_rows,
       (SELECT COUNT(*) FROM blacklist) AS bl_rows,
       (SELECT COUNT(*) FROM domain_whitelist) AS dw_rows,
       (SELECT COUNT(*) FROM order_logs) AS olog_rows,
       (SELECT COUNT(*) FROM payment_logs) AS plog_rows,
       (SELECT COUNT(*) FROM webhook_logs) AS wlog_rows,
       (SELECT COUNT(*) FROM reconciliation_logs) AS rlog_rows;
